#!/usr/bin/env bash
# ============================================================
#  Защита от остановки простаивающего Always Free-инстанса.
#
#  Oracle считает инстанс «idle» за 7 дней, если одновременно:
#    CPU (95-й перцентиль) < 20%, сеть < 20%, память < 20% (только A1).
#  Торговый бот почти всё время простаивает (5-минутные свечи), поэтому
#  инстанс рискует быть остановленным без предупреждения.
#
#  Этот скрипт каждые 10 минут создаёт небольшую нагрузку на CPU и сеть,
#  чтобы 95-й перцентиль не провалился. Нагрузка мизерная: ~2-3 секунды
#  работы CPU + несколько KB трафика.
#
#  Установка (cron раз в 10 минут):
#    crontab -e
#    */10 * * * * /opt/trading-bot/deploy/oci/keepalive.sh >> /var/log/keepalive.log 2>&1
#
#  Как systemd timer — см. README (раздел про OCI).
# ============================================================
set -uo pipefail

# 1. Немного CPU (без внешних зависимостей, чистый bash + date).
#    sha1sum по /dev/urandom ~100k раз занимает доли секунды на A1.
for _ in $(seq 1 60000); do
  echo "$RANDOM$RANDOM" | sha1sum >/dev/null 2>&1 || true
done

# 2. Немного сети: локальный HTTP-запрос к своему же API (не ходит наружу).
curl -fsS -o /dev/null --max-time 5 "http://localhost:5001/api/healthz" 2>/dev/null || true

# 3. Немного памяти под нагрузкой — тоже считается в процент утилизации,
#    но не выделяем много: осмысленно только то, что уже делают боты.
echo "$(date -Is) keepalive ok" >/dev/null
